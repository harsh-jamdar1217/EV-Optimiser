CREATE TABLE IF NOT EXISTS ev_profiles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  vehicle_model VARCHAR(100) NOT NULL,
  battery_capacity REAL NOT NULL,
  motor_power REAL NOT NULL,
  vehicle_weight REAL NOT NULL,
  charging_type TEXT NOT NULL CHECK (charging_type IN ('AC Slow', 'AC Fast', 'DC Fast')),
  manufacturing_year INT NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS analysis_results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  profile_id BIGINT NOT NULL,
  analysis_type VARCHAR(100) NOT NULL,
  result_json JSONB NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  CONSTRAINT fk_analysis_results_profile
    FOREIGN KEY (profile_id) REFERENCES ev_profiles(id)
    ON DELETE CASCADE
);
